
CREATE TABLE IF NOT EXISTS penerbit (
    id_penerbit INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_penerbit VARCHAR(100) NOT NULL,
    alamat TEXT
);

CREATE TABLE IF NOT EXISTS buku (
    id_buku INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judul VARCHAR(150) NOT NULL,
    id_penerbit INTEGER NOT NULL
        REFERENCES penerbit(id_penerbit),
    stok INTEGER NOT NULL DEFAULT 0 CHECK (stok >= 0)
);

CREATE TABLE IF NOT EXISTS "user" (
    id_user INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama VARCHAR(100) NOT NULL,
    email VARCHAR(100) UNIQUE NOT NULL,
    password VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS peminjaman (
    id_peminjaman INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_user INTEGER NOT NULL REFERENCES "user"(id_user),
    id_buku INTEGER NOT NULL REFERENCES buku(id_buku),
    tanggal_pinjam DATE NOT NULL DEFAULT CURRENT_DATE,
    status VARCHAR(20) NOT NULL DEFAULT 'diajukan'
);


